export function offerPlainText(letter: OfferLetter, links: { siteUrl: string; optOutUrl: string; lines: string[] }) {
  const blocks = [
    letter.headline,
    letter.subhead,
    "",
    ...letter.paragraphs,
    "",
    "Демонстрационный сайт:",
    links.siteUrl,
    letter.shotDisclaimer,
    "",
    "Что это может дать вашему бизнесу?",
    ...letter.benefits.flatMap((item) => [item.title, item.text, ""]),
    letter.miniappTitle,
    letter.miniappLead,
    letter.miniappNote,
    ...letter.miniappFeatures.map((item) => `- ${item}`),
    "",
    letter.retentionTitle,
    letter.retentionLead,
    ...letter.retentionSteps.map((item, index) => `${index + 1}. ${item}`),
    letter.retentionClose,
    "",
  ];
  if (letter.serviceGroups.length) {
    blocks.push(letter.serviceTitle, "");
    for (const group of letter.serviceGroups) {
      blocks.push(group.title, ...group.items.map((item) => `- ${item}`), "");
    }
  }
  blocks.push(letter.ctaTitle, ...letter.ctaParagraphs, "", "Ответить:", ...links.lines, "", "Если вы не хотите получать от нас предложения, вы можете отказаться от дальнейших сообщений.", links.optOutUrl);
  return blocks.filter((line, index, list) => line !== "" || list[index - 1] !== "").join("\n");
}
