export function offerKind(category: string | null): OfferKind {
  const value = (category || "").toLowerCase();
  if (/авто|шиномонтаж|детейл|автосервис|\bсто\b/.test(value)) return "auto";
  if (/красот|салон|барбер|парикмах|маникюр|косметолог/.test(value)) return "beauty";
  if (/ресторан|кафе|кофейн|пекар|бар\b|еда/.test(value)) return "food";
  if (/медиц|клиник|стомат|врач|аптек|диагност/.test(value)) return "medical";
  if (/магазин|торгов|ритейл|бутик|shop/.test(value)) return "shop";
  return "general";
}

export function siteFactFromStatus(status: string | null | undefined): SiteFact {
  if (status === "NO_WEBSITE" || status === "SOCIAL_ONLY" || status === "AGGREGATOR_ONLY") return "none";
  if (status === "WEBSITE_EXISTS" || status === "BROKEN_WEBSITE") return "own";
  return "unknown";
}

function quoted(name: string) {
  return `«${name}»`;
}

